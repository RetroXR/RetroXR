"""Generate RetroXR/Scripts/Data/cards/sjis_table.gd, the Shift-JIS double-byte table.

Save titles on PlayStation, PlayStation 2 and Dreamcast cards are Shift-JIS, and Godot
has no Shift-JIS codec. This writes every double-byte character of code page 932 (JIS X
0208 plus the NEC and IBM rows a Japanese PlayStation could print) into a GDScript
string, one row per lead byte, so it ships in every export with no import step: the
export presets ship resources and .info files only, so a .bin table would be missing on
the Quest.

    python Tools/gen_sjis_table.py

Rows are the lead bytes 0x81-0x9F then 0xE0-0xFC; each row is the trail bytes 0x40-0xFC
(189 characters), U+FFFD where the pair is not a character. Sjis reads it.
"""
import os
import sys

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAIL_FIRST, TRAIL_LAST = 0x40, 0xFC
PLACEHOLDER = "�"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "RetroXR",
                   "Scripts", "Data", "cards", "sjis_table.gd")


def row(lead):
    chars = []
    for trail in range(TRAIL_FIRST, TRAIL_LAST + 1):
        try:
            ch = bytes([lead, trail]).decode("cp932")
        except UnicodeDecodeError:
            ch = PLACEHOLDER
        # One code point, never ASCII (a quote or backslash would end or escape the
        # GDScript string) and never a line break (rows are split on them).
        # Nor the private-use area cp932 maps its user-defined rows (F0-F9) into:
        # no font draws those.
        if len(ch) != 1 or ord(ch) < 0x80 or ch in "  \u0085" \
                or 0xE000 <= ord(ch) <= 0xF8FF:
            ch = PLACEHOLDER
        chars.append(ch)
    return "".join(chars)


def main():
    rows = [row(lead) for lead in LEADS]
    defined = sum(len(r) - r.count(PLACEHOLDER) for r in rows)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("## SjisTable -- the Shift-JIS (code page 932) double-byte characters, for Sjis.\n")
        f.write("##\n")
        f.write("## GENERATED by Tools/gen_sjis_table.py: do not edit. One row per lead byte\n")
        f.write("## (0x81-0x9F, then 0xE0-0xFC), each row the trail bytes 0x40-0xFC, U+FFFD where\n")
        f.write("## the pair is no character. %d characters.\n" % defined)
        f.write("class_name SjisTable\n\n")
        f.write("const TRAIL_FIRST := 0x%02X\n" % TRAIL_FIRST)
        f.write("const TRAIL_COUNT := %d\n" % (TRAIL_LAST - TRAIL_FIRST + 1))
        f.write("const ROW_COUNT := %d\n\n" % len(LEADS))
        f.write('const ROWS := """\n')
        for r in rows:
            f.write(r + "\n")
        f.write('"""\n')
    print("wrote %s: %d rows, %d characters" % (os.path.normpath(OUT), len(rows), defined))
    return 0


if __name__ == "__main__":
    sys.exit(main())
